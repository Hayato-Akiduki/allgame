games.quiz = function(el) {
  const questions = quizShuffle(QUIZ_DATA).slice(0,10).map(q=>{
    const options=quizShuffle(q.opts.map((text,i)=>({text,correct:i===q.a})));
    return {...q,opts:options.map(o=>o.text),a:options.findIndex(o=>o.correct)};
  });
  let idx=0, score=0, answered=false, finished=false;
  onGameKey(key=>{
    if(finished)return false;
    const i=['1','2','3','4'].indexOf(key);
    if(i>=0&&!answered){answer(i);return true;}
    if(key==='Enter'&&answered){el.querySelector('#quiz-next')?.click();return true;}
    return false;
  });
  function render(){
    answered=false;
    const q=questions[idx];
    el.innerHTML=`<div class="game-header"><h2>❓ 雑学クイズ</h2><p>問${idx+1}/10 ・ 正解 ${score} ・ 全${QUIZ_DATA.length}問から出題</p></div>
      <div class="quiz-progress"><div class="quiz-bar" style="width:${idx*10}%"></div></div>
      <div class="quiz-q">${escapeHtml(q.q)}</div><div class="quiz-options" id="quiz-opts" data-nav-group="quiz"></div><p class="kbd-hint center mt"><kbd>1</kbd>〜<kbd>4</kbd> で回答、<kbd>Enter</kbd> で次へ</p>
      <div id="quiz-msg" role="status" style="margin-top:16px;line-height:1.7"></div>
      <button class="btn mt" id="quiz-next" hidden>${idx===9?'結果を見る':'次の問題へ'}</button>`;
    const opts=el.querySelector('#quiz-opts');
    q.opts.forEach((o,i)=>{const b=document.createElement('button');b.className='quiz-opt';b.setAttribute('data-nav','');b.innerHTML=`<span class="kbd-hint"><kbd>${i+1}</kbd></span> ${escapeHtml(o)}`;b.setAttribute('aria-label',`${i+1}：${o}`);b.onclick=()=>answer(i);opts.appendChild(b);});
    if(keyboardMode)opts.firstChild.focus();
    el.querySelector('#quiz-next').onclick=()=>{if(!answered||finished)return;idx++;if(idx<10)render();else end();};
  }
  function answer(i){
    if(answered||finished)return;answered=true;
    const q=questions[idx],buttons=el.querySelectorAll('.quiz-opt');
    buttons.forEach(b=>b.disabled=true);buttons[q.a].classList.add('correct');
    if(i===q.a)score++;else buttons[i].classList.add('wrong');
    el.querySelector('#quiz-msg').innerHTML=`<strong>${i===q.a?'✅ 正解！':'❌ 正解は「'+escapeHtml(q.opts[q.a])+'」'}</strong><p>${escapeHtml(q.exp||'正解は「'+q.opts[q.a]+'」です。')}</p>`;
    const next=el.querySelector('#quiz-next');next.hidden=false;next.focus();
  }
  function end(){
    if(finished)return;finished=true;const pts=score*15;
    if(score>=7)recordWin('quiz',pts);else{addScore(pts,'quiz');recordLoss(pts,'quiz');}
    el.innerHTML=`<div class="game-header"><h2>❓ クイズ結果</h2></div><div class="result-box"><div class="result-score">${score} / 10</div><p>スコア ${pts}点 ・ ${score>=7?'🎉 勝利！':'7問以上正解で勝利'}</p>${score>=7?xpResultHtml(pts,'quiz'):''}<button class="btn mt" onclick="startGame('quiz')">新しい10問に挑戦</button></div>`;
  }
  render();
};
function quizShuffle(items){
  const result=[...items];for(let i=result.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[result[i],result[j]]=[result[j],result[i]];}return result;
}


